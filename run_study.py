"""Run the complete study and write tables, figures and outputs/summary.md.

    python run_study.py
"""
from pathlib import Path

import pandas as pd

from gridstudy.contingency import n1_analysis
from gridstudy.hosting import wind_hosting
from gridstudy.network import base_case, build_network
from gridstudy.report import plot_hosting, plot_n1, plot_timeseries
from gridstudy.shortcircuit import short_circuit_table
from gridstudy.timeseries import Scenario, make_profiles, rating_comparison, run_timeseries

OUT = Path("outputs")
NEW_WIND_MW, NEW_WIND_PF = 10.0, 0.90


def main():
    OUT.mkdir(exist_ok=True)
    md = ["# Study summary (auto-generated by run_study.py)\n"]

    # 1. Base case ---------------------------------------------------------------------
    base = base_case(build_network())
    pd.Series(base).to_csv(OUT / "base_case.csv", header=["value"])
    md.append("## 1. Base-case power flow (CIGRE MV, peak demand)\n")
    md.append(pd.Series(base).round(3).to_frame("value").to_markdown() + "\n")

    # 2. Short circuit -----------------------------------------------------------------
    sc = short_circuit_table(build_network())
    sc.to_csv(OUT / "short_circuit.csv", index_label="bus_id")
    md.append("## 2. Three-phase short circuit (IEC 60909)\n")
    md.append(sc.round(3).to_markdown() + "\n")

    # 3. N-1 + restoration -------------------------------------------------------------
    n1 = n1_analysis(build_network())
    n1.to_csv(OUT / "n1.csv", index=False)
    plot_n1(n1, OUT / "fig_n1.png")
    md.append("## 3. N-1 security with tie-switch restoration\n")
    md.append(n1.round(3).to_markdown(index=False) + "\n")

    # 4. Time series + rating ----------------------------------------------------------
    profiles = make_profiles()
    net = build_network(new_wind_mw=NEW_WIND_MW, new_wind_pf=NEW_WIND_PF)
    summary, loading = run_timeseries(net, profiles, Scenario())
    cmp, loading_adj = rating_comparison(net, loading, profiles.ambient_c)
    summary.join(profiles).to_csv(OUT / "timeseries_summary.csv")
    cmp.to_csv(OUT / "rating_comparison.csv", index=False)
    plot_timeseries(summary, loading, loading_adj, "Line 13-14", OUT / "fig_timeseries.png")
    md.append(f"## 4. Synthetic week, new {NEW_WIND_MW:.0f} MW wind plant at bus 14 (cos φ = {NEW_WIND_PF})\n")
    md.append(f"- hours with Vmin < 0.95 p.u.: {(summary.vmin_pu < 0.95).sum()} (base-network issue at evening peak)")
    md.append(f"- hours with Vmax > 1.05 p.u.: {(summary.vmax_pu > 1.05).sum()}\n")
    md.append(cmp.round(2).to_markdown(index=False) + "\n")

    # 5. Hosting capacity --------------------------------------------------------------
    rows = []
    for pf in (0.95, 0.90):
        for t in (40, 35, 30, 25, 20):
            _, mw, why = wind_hosting(ambient_c=t, pf=pf)
            rows.append({"pf": pf, "ambient_c": t, "hosting_mw": mw, "limited_by": why})
    hosting = pd.DataFrame(rows)
    hosting.to_csv(OUT / "hosting.csv", index=False)
    plot_hosting(hosting, OUT / "fig_hosting.png")
    md.append("## 5. Wind hosting capacity at bus 14 (minimum demand, full output)\n")
    md.append(hosting.to_markdown(index=False) + "\n")

    (OUT / "summary.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
